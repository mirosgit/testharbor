@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("test_login_C142", [142]),
        ("C142 login works", [142]),
        ("[C142][C7] login", [142, 7]),
        ("login (C142)", [142]),
        ("test_ABC142", []),
        ("TC142 login", []),
        ("test_c142", []),  # lowercase is not treated as a case id
        ("version C1.2", [1]),
        ("C1234567890123x", [1234567890123]),
    ],
)
def test_case_id_in_name(name: str, expected: list[int]) -> None:
    assert JUnitCase(name=name).case_ids() == expected


def test_case_id_property_variants() -> None:
    t = JUnitCase(name="x", properties={"case_id": ["C1, c2 3"], "Case_IDs": ["C4"]})
    assert t.case_ids() == [1, 2, 3, 4]
    # Property wins over the name.
    assert JUnitCase(name="test_C9", properties={"case_id": ["C1"]}).case_ids() == [1]


def test_pytest_key_candidates_from_dotted_classname() -> None:
    t = JUnitCase(name="test_create", classname="tests.api.test_orders.TestOrders")
    keys = t.candidate_keys()
    assert "tests/api/test_orders.py::TestOrders::test_create" in keys
    assert keys.index("tests.api.test_orders.TestOrders::test_create") == 0


@pytest.mark.parametrize(
    "xml",
    [
        b"not xml at all",
        b"<html><body/></html>",
        b'<?xml version="1.0"?><!DOCTYPE lolz [<!ENTITY lol "lol"><!ENTITY lol2 "&lol;&lol;">]>'
        b"<testsuite><testcase name='&lol2;'/></testsuite>",
        b'<?xml version="1.0"?><!DOCTYPE x [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>'
        b"<testsuite><testcase name='&xxe;'/></testsuite>",
    ],
)
def test_rejects_bad_or_malicious_xml(xml: bytes) -> None:
    with pytest.raises(JUnitParseError):
        parse_junit(xml)


def test_minimal_and_nested_suites() -> None:
    xml = b"""<testsuites><testsuite name="outer"><testsuite name="inner">
        <testcase name="a" time="1,234.5"/><testcase name="b"><error/></testcase>
        </testsuite></testsuite></testsuites>"""
    a, b = parse_junit(xml)
    assert a.duration_ms() == 1234500 and a.status is ResultStatus.passed
    assert b.status is ResultStatus.failed and b.message == "[error]"


