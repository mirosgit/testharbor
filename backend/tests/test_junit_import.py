FIXTURES = Path(__file__).parent / "fixtures" / "junit"


def load(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


# --- Parser --------------------------------------------------------------------------


def test_parse_pytest_with_plugin() -> None:
    tests = {t.name: t for t in parse_junit(load("pytest-xunit2.xml"))}
    assert len(tests) == 10
    assert tests["test_login_C1"].case_ids() == [1]
    assert tests["test_wrong_password"].case_ids() == [2]
    assert tests["test_lockout_and_unlock"].case_ids() == [3, 4]
    assert tests["test_wrong_password"].status is ResultStatus.failed
    assert "expected 401" in tests["test_wrong_password"].message
    assert "tests/test_auth.py:14: AssertionError" in tests["test_wrong_password"].details
    assert tests["test_sso_login"].status is ResultStatus.skipped
    assert tests["test_sso_login"].message == "SSO provider not configured"
    assert tests["test_profile_page"].status is ResultStatus.failed
    assert tests["test_profile_page"].message.startswith("[error]")
    assert tests["test_create_order"].explicit_key() == "tests/api/test_orders.py::TestOrders::test_create_order"
    assert "POST /orders -> 201" in (tests["test_create_order"].details or "")


def test_parse_playwright() -> None:
    tests = {t.name: t for t in parse_junit(load("playwright.xml"))}
    assert len(tests) == 4
    assert tests["Login › C1 login with valid credentials"].case_ids() == [1]
    wrong = tests["Login › shows an error for a wrong password"]
    assert wrong.case_ids() == [2]  # from the case_id annotation property
    assert wrong.status is ResultStatus.failed
    assert "toBeVisible" in wrong.message
    assert wrong.time_s and wrong.duration_ms() == round(wrong.time_s * 1000)
    assert tests["Login › remember me [C6]"].status is ResultStatus.skipped
    assert tests["Login › remember me [C6]"].case_ids() == [6]
    assert tests["signup form renders"].case_ids() == []


def test_parse_surefire_junit5() -> None:
    tests = {t.name: t for t in parse_junit(load("surefire-junit5.xml"))}
    assert set(tests) == {"payWithCard_C1", "threeDSecure_C3", "applyDiscountCode", "refund_C6", "declinedCard_C2"}
    assert tests["declinedCard_C2"].status is ResultStatus.failed
