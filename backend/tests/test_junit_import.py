    body = (await _import(client, pid, "pytest-xunit2.xml", auto_create="true")).json()
    assert (body["matched"], body["created"], body["unmatched"]) == (8, 2, [])

    suites = (await client.get(f"/api/projects/{pid}/suites")).json()
    unsorted = next(s for s in suites if s["name"] == "Unsorted")
    sections = (await client.get(f"/api/suites/{unsorted['id']}/sections")).json()
    assert [s["name"] for s in sections] == ["Automated"]
    created = (await client.get(f"/api/projects/{pid}/cases", params={"suite_id": unsorted["id"]})).json()
