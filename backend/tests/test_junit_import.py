    assert by_title["test_refund_order"]["automation_status"] == "automated"
    assert by_title["test_profile_page"]["automation_key"] == "tests/test_auth.py::test_profile_page"

    # Second import: everything matches, nothing new is created, same suite/section reused.
    again = (await _import(client, pid, "pytest-xunit2.xml", auto_create="true")).json()
    assert (again["matched"], again["created"], again["unmatched"]) == (10, 0, [])
    assert len((await client.get(f"/api/projects/{pid}/suites")).json()) == len(suites)


