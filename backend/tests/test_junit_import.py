async def test_token_lifecycle_and_bearer_import(client: AsyncClient, project) -> None:  # type: ignore[no-untyped-def]
    from httpx import ASGITransport

    from app.main import app

    r = await client.post("/api/tokens", json={"name": "CI"})
    assert r.status_code == 201
    token = r.json()["token"]
    assert token.startswith("th_") and r.json()["prefix"] == token[:10]
    listed = (await client.get("/api/tokens")).json()
    assert "token" not in listed[0] and listed[0]["last_used_at"] is None

    headers = {"Authorization": f"Bearer {token}"}
    # A separate client with only the Bearer token (no session cookie).
    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as bot:
        r = await bot.post(f"/api/projects/{project['id']}/runs/import-junit", headers=headers,
                           files={"file": ("p.xml", load("playwright.xml"), "application/xml")})
        assert r.status_code == 200, r.text
        me = (await bot.get("/api/auth/me", headers=headers)).json()
        assert (me["email"], me["via"]) == ("admin@example.com", "token")
        # Tokens can't manage tokens (a leaked CI token must not mint new ones).
        assert (await bot.post("/api/tokens", headers=headers, json={"name": "x"})).status_code == 403
        assert (await client.get("/api/tokens")).json()[0]["last_used_at"] is not None

        # Wrong / revoked tokens are rejected.
        assert (await bot.get("/api/projects", headers={"Authorization": "Bearer th_nope"})).status_code == 401
        assert (await client.delete(f"/api/tokens/{listed[0]['id']}")).status_code == 204
        assert (await bot.get("/api/projects", headers=headers)).status_code == 401
        assert (await client.get("/api/tokens")).json()[0]["revoked_at"] is not None


