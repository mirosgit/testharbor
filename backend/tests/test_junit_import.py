async def test_auto_create_then_reimport_matches(client: AsyncClient, project) -> None:  # type: ignore[no-untyped-def]
    pid = project["id"]
    body = (await _import(client, pid, "pytest-xunit2.xml", auto_create="true")).json()
    assert (body["matched"], body["created"], body["unmatched"]) == (8, 2, [])

    suites = (await client.get(f"/api/projects/{pid}/suites")).json()
    unsorted = next(s for s in suites if s["name"] == "Unsorted")
    sections = (await client.get(f"/api/suites/{unsorted['id']}/sections")).json()
    assert [s["name"] for s in sections] == ["Automated"]
    created = (await client.get(f"/api/projects/{pid}/cases", params={"suite_id": unsorted["id"]})).json()
    by_title = {c["title"]: c for c in created["items"]}
    assert by_title["test_refund_order"]["automation_key"] == "tests/api/test_orders.py::TestOrders::test_refund_order"
    assert by_title["test_refund_order"]["automation_status"] == "automated"
    assert by_title["test_profile_page"]["automation_key"] == "tests/test_auth.py::test_profile_page"

    # Second import: everything matches, nothing new is created, same suite/section reused.
    again = (await _import(client, pid, "pytest-xunit2.xml", auto_create="true")).json()
    assert (again["matched"], again["created"], again["unmatched"]) == (10, 0, [])
    assert len((await client.get(f"/api/projects/{pid}/suites")).json()) == len(suites)


