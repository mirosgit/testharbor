async def _import(client: AsyncClient, pid: int, *names: str, **params):  # type: ignore[no-untyped-def]
    files = [("file", (n, load(n), "application/xml")) for n in names]
    return await client.post(f"/api/projects/{pid}/runs/import-junit", files=files, params=params)


async def _statuses(client: AsyncClient, run_id: int) -> dict[str, str]:
    return {c["key"]: c["status"] for c in (await client.get(f"/api/runs/{run_id}/cases")).json()}


async def test_import_pytest_with_plugin(client: AsyncClient, project) -> None:  # type: ignore[no-untyped-def]
    r = await _import(client, project["id"], "pytest-xunit2.xml", run_name="Nightly #123",
                      branch="main", commit="abc123", build_url="https://ci/1")
    assert r.status_code == 200, r.text
    body = r.json()
    assert (body["total"], body["matched"], body["created"]) == (10, 8, 0)
    assert sorted(u["name"] for u in body["unmatched"]) == ["test_profile_page", "test_refund_order"]
    assert body["statuses"] == {"passed": 6, "failed": 2, "skipped": 1}  # C3+C4 share one test

    run = (await client.get(f"/api/runs/{body['run_id']}")).json()
    assert (run["name"], run["source"], run["branch"], run["commit"], run["build_url"]) == (
        "Nightly #123", "ci", "main", "abc123", "https://ci/1"
    )
    assert await _statuses(client, body["run_id"]) == {
        "C1": "passed", "C2": "failed", "C3": "passed", "C4": "passed",
        "C5": "failed",  # parametrized: chrome passed, firefox failed -> worst wins
        "C6": "skipped", "C7": "passed", "C8": "passed",
    }
    # Both parametrized results are kept, labelled with the test name.
    hist = (await client.get(f"/api/runs/{body['run_id']}/cases/C5/results")).json()
    assert [(h["status"], h["comment"]) for h in hist] == [
        ("failed", "tests.test_auth::test_logout[firefox]"),
        ("passed", "tests.test_auth::test_logout[chrome]"),
    ]
    assert "logout button hidden in firefox" in hist[0]["error_message"]
    assert "tests/test_auth.py:25" in hist[0]["stack_trace"]


